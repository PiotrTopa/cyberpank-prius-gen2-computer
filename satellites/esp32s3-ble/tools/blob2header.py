#!/usr/bin/env python3
"""
blob2header — turn a ``prius-satkey new NAME --transport ble -o blob.json``
provisioning blob into ``esp32s3_ble/provision.h`` for the BLE satellite.

    tools/blob2header.py BLOB.json [-o esp32s3_ble/provision.h] [--car-addr AA:BB:..]

The header carries the satellite's Ed25519 private key — it is listed in
.gitignore and must never be committed. Checks done here so the firmware does
not have to: fp == fingerprint(pubkey), car_fp == fingerprint(car_pub),
transport == "ble", privkey present, cert (if any) names the same fp.

``--car-addr`` overrides ``ble.car_addr`` (the car's fixed public address,
02:00:E8:51:02:58 on the phone) — use it on a bench where another BlueZ adapter
plays the car; ``--car-addr any`` disables the address preference (the
satellite then takes the first advertiser of the service UUID).
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import sys

SERVICE_UUID = "580e04f7-d4c0-458b-b2e0-4ebb01a960c8"
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "esp32s3_ble", "provision.h")


def fingerprint(raw: bytes) -> str:
    return base64.b32encode(hashlib.sha256(raw).digest()[:16]).decode().rstrip("=").lower()


def c_bytes(raw: bytes) -> str:
    return ", ".join("0x%02x" % b for b in raw)


def c_str(text: str) -> str:
    return json.dumps(text)  # JSON string escaping is valid C for ASCII content


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("blob")
    ap.add_argument("-o", "--out", default=DEFAULT_OUT)
    ap.add_argument("--car-addr", default=None)
    args = ap.parse_args()

    with open(os.path.expanduser(args.blob)) as fh:
        blob = json.load(fh)
    die = lambda msg: sys.exit("blob2header: " + msg)
    if blob.get("transport") != "ble":
        die("transport is %r, need 'ble' (prius-satkey new NAME --transport ble)" % blob.get("transport"))
    if "privkey" not in blob:
        die("blob has no privkey (use the output of 'prius-satkey new', not 'show'/'sign')")
    priv = base64.b64decode(blob["privkey"])
    pub = base64.b64decode(blob["pubkey"])
    car_pub = base64.b64decode(blob["car_pub"])
    if len(priv) != 32 or len(pub) != 32 or len(car_pub) != 32:
        die("key lengths must be 32 bytes")
    fp = fingerprint(pub)
    if blob.get("fp") and blob["fp"] != fp:
        die("fp does not match pubkey")
    car_fp = fingerprint(car_pub)
    if blob.get("car_fp") and blob["car_fp"] != car_fp:
        die("car_fp does not match car_pub")
    cert = blob.get("cert")
    if cert is not None and (cert.get("fp") != fp or cert.get("transport") != "ble"):
        die("cert does not match fp/transport")
    # Compact JSON; the car canonicalises the parsed object itself (sort_keys),
    # so key order here does not matter. Keep ASCII so it is a plain C string.
    cert_json = json.dumps(cert, separators=(",", ":"), ensure_ascii=True) if cert else ""
    name = str(blob.get("name") or "sat")
    sat_id = int(blob.get("sat_id") or 0)
    car_addr = args.car_addr if args.car_addr is not None else (blob.get("ble") or {}).get("car_addr", "")
    car_addr = "" if car_addr in (None, "any") else str(car_addr).upper()
    if car_addr and not re.match(r"^[0-9A-F]{2}(:[0-9A-F]{2}){5}$", car_addr):
        die("bad car address %r" % car_addr)
    service = (blob.get("ble") or {}).get("service", SERVICE_UUID)
    if service.lower() != SERVICE_UUID:
        die("unexpected service UUID %r" % service)

    out = f"""// GENERATED by tools/blob2header.py from {os.path.basename(args.blob)} — DO NOT COMMIT
// (contains the satellite's Ed25519 private key).
#pragma once
#include <stdint.h>

#define PROV_SAT_ID      {sat_id}
#define PROV_NAME        {c_str(name)}
#define PROV_TRANSPORT   "ble"
#define PROV_FP          {c_str(fp)}
#define PROV_PUBKEY_B64  {c_str(blob["pubkey"])}
#define PROV_CAR_FP      {c_str(car_fp)}
#define PROV_CAR_ADDR    {c_str(car_addr)}   // "" = any advertiser of the service
#define PROV_CERT_JSON   {c_str(cert_json)}  // "" = no cert (needs enrolment)

static const uint8_t PROV_PRIVKEY[32] = {{ {c_bytes(priv)} }};
static const uint8_t PROV_PUBKEY[32]  = {{ {c_bytes(pub)} }};
static const uint8_t PROV_CAR_PUB[32] = {{ {c_bytes(car_pub)} }};
"""
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    fd = os.open(args.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(out)
    print(f"wrote {args.out}: sat {sat_id} {name} fp {fp} car {car_fp} car_addr {car_addr or 'any'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
